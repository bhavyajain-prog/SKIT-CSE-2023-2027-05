-- One row per generation run. Sessions and their placements now belong to a
-- timetable, so several generated timetables can be kept and compared.
CREATE TABLE timetables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    week_days INTEGER NOT NULL,
    max_slots INTEGER NOT NULL,
    lunch_start INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

ALTER TABLE sessions ADD COLUMN timetable_id BIGINT REFERENCES timetables (id);
ALTER TABLE sessions ADD COLUMN slot_duration INTEGER NOT NULL DEFAULT 1;

ALTER TABLE scheduled_sessions ADD COLUMN timetable_id BIGINT REFERENCES timetables (id);

CREATE INDEX idx_sessions_timetable_id ON sessions (timetable_id);
CREATE INDEX idx_scheduled_sessions_timetable_id ON scheduled_sessions (timetable_id);
